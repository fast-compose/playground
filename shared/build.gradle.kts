/**
 * Generates `BuildInfo.kt` into a source set every target compiles: an object with one string constant per entry of
 * [constants].
 */
abstract class GenerateBuildInfo : DefaultTask() {

    @get:Input
    abstract val packageName: Property<String>

    @get:Input
    abstract val constants: MapProperty<String, String>

    @get:OutputDirectory
    abstract val outputDir: DirectoryProperty

    @TaskAction
    fun generate() {
        val pkg = packageName.get()
        val file = outputDir.get().asFile
            .resolve(pkg.replace('.', '/'))
            .resolve("BuildInfo.kt")
        file.parentFile.mkdirs()
        val fields = constants.get().entries.joinToString("\n") { (name, value) ->
            "    const val $name: String = \"$value\""
        }
        file.writeText(
            "package $pkg\n\n" +
                "/** Generated by the `generateBuildInfo` task from the version catalog - do not edit. */\n" +
                "object BuildInfo {\n$fields\n}\n"
        )
    }
}
